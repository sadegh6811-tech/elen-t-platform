#!/bin/bash

echo "🤖 [ربات دیپلوی جامع]: شروع عملیات اتوماتیک..."
echo "=================================================="
echo "⚠️ توجه: برای این کار نیاز به یک توکن جدید گیت‌هاب دارید."
echo "اگر توکن ندارید، به GitHub.com -> Settings -> Developer settings -> Personal access tokens بروید و یک توکن با دسترسی 'repo' بسازید."
echo "=================================================="

# ۱. دریافت توکن جدید از کاربر
read -p "🔑 لطفاً توکن جدید گیت‌هاب خود (که با ghp_ شروع می‌شود) را پیست کنید و Enter بزنید: " NEW_TOKEN

if [ -z "$NEW_TOKEN" ]; then
    echo "❌ خطا: توکن وارد نشد. عملیات لغو شد."
    exit 1
fi

# ۲. ذخیره توکن (بدون کاراکتر اضافه)
echo -n "$NEW_TOKEN" > ~/.github_token
echo "✅ توکن جدید با موفقیت در سیستم ذخیره شد."

# ۳. رفتن به پوشه پروژه و اجرای اسکریپت پچ‌کننده
echo "🚀 [مرحله ۲]: در حال اجرای اسکریپت تزریق کدها و پوش به گیت‌هاب..."
cd ~/Nazi/auth-portal-clean || { echo "❌ پوشه پروژه پیدا نشد!"; exit 1; }

python3 activate_security_shield.py

if [ $? -eq 0 ]; then
    echo "=================================================="
    echo "🎉 [ربات]: کدهای موتور ریاضی و امنیتی با موفقیت به گیت‌هاب ارسال شدند!"
    echo "⚠️ [مهم‌ترین قدم نهایی]: حالا به داشبورد Render.com بروید، پروژه elen-backend-v2 را باز کنید و روی 'Manual Deploy' کلیک کنید تا سرور با کدهای جدید آپدیت شود."
    echo "=================================================="
else
    echo "❌ [ربات]: خطا در اجرای اسکریپت پایتون. لطفاً لاگ‌های بالا را بررسی کنید."
fi
